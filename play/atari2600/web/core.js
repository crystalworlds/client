/* play/atari2600/web/core.js — the Atari 2600 core, wrapped at its documented ABI.
 *
 * SITE-OWNED, AND THAT IS A DIVERGENCE FROM play/nes/ WORTH STATING.
 * -----------------------------------------------------------------------------
 * play/nes/web/ is vendored BYTE-IDENTICAL from the NES core's own project, and the NES
 * constitution says so: the site may use those modules only through their
 * published exports and may never patch them. That arrangement needs the core's
 * project to HAVE a module layer. The Atari project does not. Its `web/shell.js` is a
 * test PAGE — it reads `$('scheme').value`, writes `$('status').textContent`,
 * owns file inputs and a test bench — so there is nothing in it that could be
 * vendored into a site play page without dragging its DOM along.
 *
 * So this file exists, and the contract it keeps instead is narrower and
 * written down here:
 *
 *   * IT TOUCHES THE CORE ONLY THROUGH the core interface. Every call below is
 *     a function that document names, used as that document describes. No
 *     reading of core memory except through an address the ABI returned, no
 *     assumption about the framebuffer's shape beyond the 160 x 320 the
 *     document states, no reimplementation of anything the core does.
 *   * A CORE DEFECT IS FIXED IN THE CORE and arrives here as a new artifact.
 *     Nothing in this directory is edited to work around one.
 *   * TWO FILES BESIDE THIS ONE *ARE* VENDORED BYTE-IDENTICAL, because they
 *     could be: web/palette.js (generated by the palette generator) and
 *     web/audio-worklet.js. Their hashes are pinned in CORE-VERSION.json and
 *     WASM_Source/atari/verify.sh fails on drift. Do not edit them here.
 *
 * WHAT MAKES A CORE SWAP CHEAP, which is the whole point of this integration
 * -----------------------------------------------------------------------------
 * The emulators are still being tested and will be replaced. So the cost of a
 * swap had to be designed down to: drop a new `build/atari2600.wasm` in, run
 * `node tools/stamp.mjs`, done. Three things hold that together:
 *
 *   1. NOTHING HERE HARD-CODES A CORE HASH. The hash lives in CORE-VERSION.json,
 *      which is DATA — generated in full, never branched on.
 *   2. REQUIRED IS ASSERTED, NOT ASSUMED. `REQUIRED` below is every export this
 *      page actually calls. instantiate() checks all of them against the module
 *      and throws naming the MISSING ONES if any is absent. A core built with a
 *      renamed or dropped export therefore fails at load, loudly, with the list
 *      — rather than producing a black screen, a silent catch, or an
 *      undefined-is-not-a-function thrown from inside the frame loop where
 *      nobody will connect it to the swap. The ABI document promises scheme
 *      numbers never change once given; it promises nothing about export names
 *      surviving a rewrite, so that is the thing to check.
 *   3. OPTIONAL IS SEPARATE FROM REQUIRED. `OPTIONAL` is the set this page uses
 *      if present and does without if not (NVRAM, EEPROM, save states). A core
 *      that drops one of those degrades a feature; it does not fail to load.
 *      Mixing the two lists is how a check like this ends up disabled.
 *
 * MEMORY. The module exports its memory and imports nothing. `atari_create()`
 * grows memory for one machine context and returns its address; every other
 * buffer is the host's problem. Growth DETACHES the old ArrayBuffer, so this
 * file grows ONCE, up front, for everything it will ever need, and re-takes
 * `memory.buffer` through `u8()` on every access rather than caching a view.
 * A cached view that survives a grow is the classic way to read zeroes from a
 * detached buffer and conclude the core is broken.
 */

/* The raster the core hands back: 320 rows of 160 bytes, every row the beam
 * drew between one VSYNC and the next. Stated by the core interface, "Video". */
export const RASTER_W = 160;
export const RASTER_H = 320;

/* What a television would actually show of that raster, per the same section:
 * rows 23 to 250 are shown for NTSC and 32 to 305 for PAL and SECAM.
 * Keyed by the region number atari_set_region takes. */
export const WINDOW = {
  0: { y: 23, h: 228 },   // NTSC
  1: { y: 32, h: 274 },   // PAL
  2: { y: 32, h: 274 },   // SECAM
};

/* CPU rates, from the core interface "Timing": NTSC 1,193,182 cycles a second,
 * PAL 1,182,298. Written as the colour-carrier division they actually are, so
 * the provenance of the figure is in the expression rather than in a comment
 * that can drift from it. */
export const CPU_HZ = { 0: 3579545 / 3, 1: 3546894 / 3, 2: 3546894 / 3 };

/* Audio arrives at two samples a scanline — about 31,400/s NTSC. The worklet
 * needs the input rate to resample against the device rate. */
export const AUDIO_HZ = { 0: 2 * 3579545 / 228, 1: 2 * 3546894 / 228, 2: 2 * 3546894 / 228 };

/* Scheme numbers, in the order atari_scheme_name gives them. the core interface:
 * "numbers never change once given". 0 is AUTO and is what this page uses —
 * the list is here so a reported scheme can be NAMED in the status line rather
 * than shown as an integer. */
export const SCHEMES = [
  'AUTO', '2K', '4K', 'F8', 'F6', 'F4', 'F8SC', 'F6SC', 'F4SC', 'E0', 'FE', '3F',
  'FA', 'E7', 'DPC', '4KSC', '3E', 'AR', 'UA', 'CV', 'EF', 'EFSC', 'BF', 'BFSC',
  'DF', 'DFSC', 'SB', 'FA2', 'CTY', 'MDM', '0840', '3EPlus', 'WD', 'E78K',
  'X07', 'TVBOY', 'JANE', 'MVCOLD', 'UASW', 'GL', 'WDSW', 'FC', 'TV8IN1',
  '2IN1', '4IN1', '8IN1', '16IN1', '32IN1', '64IN1', '128IN1', 'MVC', 'DPCPLUS',
  'CDF', 'BUS', 'ELF',
];

/* EVERY EXPORT THIS PAGE CALLS. See the header: this is asserted at load.
 * Keep it in step with what app.js and this file actually use — a name left
 * here that nothing calls makes the check stricter than it needs to be and
 * will reject a core that would have worked. */
const REQUIRED = [
  'memory',
  'atari_create', 'atari_init', 'atari_sizeof_context',
  'atari_load_cartridge', 'atari_scheme_reason', 'atari_scheme_name',
  'atari_set_region', 'atari_power_on',
  'atari_run_frame', 'atari_raster', 'atari_raster_lines',
  'atari_frame_scanlines', 'atari_cpu_cycles',
  'atari_set_joystick', 'atari_set_switches', 'atari_set_controller',
  'atari_audio_available', 'atari_audio_read',
];

/* Used when present, done without when absent. A core that drops one of these
 * loses a feature and still loads — which is the difference between this list
 * and REQUIRED, and the reason they are two lists. */
const OPTIONAL = [
  'atari_nvram', 'atari_nvram_size', 'atari_nvram_load',
  'atari_eeprom', 'atari_eeprom_changed',
  'atari_state_size', 'atari_state_save', 'atari_state_load',
  'atari_set_paddle', 'atari_set_paddle_fire', 'atari_peek_ram', 'atari_cpu_pc',
];

/* Scratch space this page asks the module for, once, before anything runs:
 *   512 KB  the largest cartridge atari_load_cartridge accepts
 *     8 KB  the audio drain buffer (the core keeps at most 4,095 samples)
 * Rounded to whole 64 KB pages. Growing later would detach every view in
 * flight, so it is all taken up front — see MEMORY in the header. */
const CART_MAX = 512 * 1024;
const AUDIO_BUF = 8 * 1024;
const SCRATCH = CART_MAX + AUDIO_BUF;

export class Core {
  constructor(instance) {
    const X = instance.exports;
    this.X = X;
    this.memory = X.memory;

    /* The context. atari_create() grows memory itself and returns the address
     * of a powered-on machine with no cartridge. 0 means it could not. */
    this.ctx = X.atari_create();
    if (!this.ctx) throw new Error('atari_create() returned 0: the core could not allocate a machine context');

    /* Scratch AFTER the context, so the core's own growth has already happened
     * and this is the last grow of the session. memory.grow returns the OLD
     * page count, so the new region starts there. */
    const pages = Math.ceil(SCRATCH / 65536);
    const old = this.memory.grow(pages);
    this.scratch = old * 65536;
    this.scratchSize = pages * 65536;
    this.audioBuf = this.scratch + this.scratchSize - AUDIO_BUF;

    this.region = 0;
    this.scheme = 0;
    this.schemeReason = '';
  }

  /* Never cached. Every grow detaches the previous ArrayBuffer, and a view
   * held across one reads zeroes without throwing. */
  u8(ptr, n) { return new Uint8Array(this.memory.buffer, ptr, n); }

  cstr(ptr) {
    const b = new Uint8Array(this.memory.buffer, ptr, 256);
    let n = 0;
    while (n < 256 && b[n]) n++;
    return new TextDecoder().decode(b.subarray(0, n));
  }

  setRegion(r) {
    /* Set BEFORE loading, per the core interface: it affects the frame-length
     * fallback and the DPC oscillator. */
    this.region = r | 0;
    this.X.atari_set_region(this.ctx, this.region);
  }

  /* Returns the scheme number the core chose, or throws. The core's own reason
   * text is kept so the page can show WHY a cartridge was read the way it was
   * — which is the only thing that makes a mis-detected scheme diagnosable
   * from the outside. */
  loadCartridge(data) {
    if (!(data instanceof Uint8Array)) throw new TypeError('loadCartridge wants a Uint8Array');
    if (data.length > CART_MAX) throw new Error(`cartridge is ${data.length} bytes; the core accepts at most ${CART_MAX}`);
    this.u8(this.scratch, data.length).set(data);
    const got = this.X.atari_load_cartridge(this.ctx, this.scratch, data.length, 0);
    this.schemeReason = this.cstr(this.X.atari_scheme_reason(this.ctx));
    if (got < 0) throw new Error(`the core refused this cartridge: ${this.schemeReason || 'no reason given'}`);
    this.scheme = got;
    return got;
  }

  /* The core's own name first (30 Oct 2026): SCHEMES above fell out of step with the core's
     numbering (from 19 on it named the wrong scheme, 19 UASW shown as "CV"); it is only the
     fallback now, for a core without atari_scheme_name. */
  schemeName(n) {
    try { const c = this.cstr(this.X.atari_scheme_name(n)); if (c && c !== '?') return c; } catch (e) {}
    const s = (n >= 0 && n < SCHEMES.length) ? SCHEMES[n] : null;
    return s || String(n);
  }

  powerOn() { this.X.atari_power_on(this.ctx); }
  runFrame() { return this.X.atari_run_frame(this.ctx); }
  cpuCycles() { return Number(this.X.atari_cpu_cycles(this.ctx)); }
  scanlines() { return this.X.atari_frame_scanlines(this.ctx); }
  raster() { return this.u8(this.X.atari_raster(this.ctx), RASTER_W * RASTER_H); }

  setJoystick(port, bits) { this.X.atari_set_joystick(this.ctx, port, bits); }
  setSwitches(bits) { this.X.atari_set_switches(this.ctx, bits); }
  setController(port, type) { this.X.atari_set_controller(this.ctx, port, type); }

  /* Drains what the core has and returns a Float32Array of the mix, or null.
   * The sum of the two 0..15 channel levels divided by 30 is the core project's own
   * mix and is FITTED — the emulation chapters say the TIA's output stage is mildly
   * non-linear and this treats it as linear. Named as fitted rather than left
   * to look like a derivation. */
  drainAudio() {
    const n = this.X.atari_audio_available(this.ctx);
    if (!n) return null;
    const got = this.X.atari_audio_read(this.ctx, this.audioBuf, Math.min(n, 4096));
    if (!got) return null;
    const b = this.u8(this.audioBuf, got);
    const f = new Float32Array(got);
    for (let i = 0; i < got; i++) f[i] = ((b[i] & 15) + (b[i] >> 4)) / 30;
    return f;
  }
}

/* Instantiate and CHECK. The throw is the point: see WHAT MAKES A CORE SWAP
 * CHEAP in the header. */
export async function instantiate(url) {
  let instance;
  try {
    ({ instance } = await WebAssembly.instantiateStreaming(fetch(url), {}));
  } catch (e) {
    /* instantiateStreaming needs the right Content-Type; a plain fetch does
     * not. Falling back keeps the page working on a static host that serves
     * .wasm as application/octet-stream, which several do. */
    const buf = await (await fetch(url)).arrayBuffer();
    ({ instance } = await WebAssembly.instantiate(buf, {}));
  }
  const X = instance.exports;
  const missing = REQUIRED.filter(k => !(k in X));
  if (missing.length) {
    throw new Error(
      `This Atari 2600 core is missing ${missing.length} export(s) this page calls: ` +
      missing.join(', ') +
      '. The artifact at ' + url + ' does not match the core interface. ' +
      'Re-stamp with tools/stamp.mjs and check CORE-VERSION.json.exports.'
    );
  }
  const core = new Core(instance);
  core.absent = OPTIONAL.filter(k => !(k in X));
  return core;
}
